"""Local deployment packaging tests; no Cloud API calls or secret reads."""

import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("prepare", ROOT / "scripts/prepare_cloud_deploy.py")
deploy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(deploy)


class PrepareTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        for name in deploy.REQUIRED:
            self.write(name, "// reviewed generated runtime output\n")
        for package in ("closecall_server", "closecall_shared"):
            self.write(package + "/pubspec.yaml",
                       (ROOT / package / "pubspec.yaml").read_text())
        self.write("closecall_shared/lib/schedule.dart", "const answer = 42;\n")
        self.write("closecall_server/pubspec.lock", """# Generated by pub
packages:
  closecall_shared:
    dependency: "direct main"
    description:
      path: "../closecall_shared"
      relative: true
    source: path
    version: "1.0.0"
  serverpod:
    dependency: "direct main"
    description:
      name: serverpod
      sha256: abc
      url: "https://pub.dev"
    source: hosted
    version: "4.0.3"
  sqlite3:
    dependency: transitive
    description:
      name: sqlite3
      sha256: def
      url: "https://pub.dev"
    source: hosted
    version: "3.7.0"
sdks:
  dart: ">=3.12.2 <4.0.0"
""")
        self.write("closecall_server/scloud.yaml", deploy.SCLOUD_CONFIG)
        self.write("closecall_server/lib/src/model.spy.yaml", "class: Model\n")
        self.write("closecall_server/migrations/20261004000100000/migration.sql", "SELECT 1;\n")
        subprocess.run(["git", "add", "closecall_server", "closecall_shared"],
                       cwd=self.root, check=True)

    def write(self, name, content):
        target = self.root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        return target

    def test_allowlisting_without_reading_private_files(self):
        denied = [
            "lib/firebase_options.dart", ".env", ".opencode/omnirush/inbox/attachment.pdf",
            ".tooling/flutter/sdk.log", "android/app/google-services.json",
            "closecall_server/config/passwords.yaml", "closecall_server/config/production.yaml",
            "closecall_server/lib/passwords.dart", "closecall_server/lib/.env.dart",
            "closecall_server/test/a_test.dart", "closecall_server/tool/generate.dart",
            "closecall_server/.serverpod/database.db", "closecall_shared/test/a_test.dart",
        ]
        for path in denied:
            self.write(path, "PRIVATE-CONTENT-MUST-NOT-BE-READ")
        # Even tracked files with a runtime-looking secret name are rejected.
        subprocess.run(["git", "add", "closecall_server/lib/passwords.dart"],
                       cwd=self.root, check=True)
        reads = []
        real_read = deploy.read_regular

        def guarded_read(root, path):
            self.assertNotIn(path, denied)
            reads.append(path)
            return real_read(root, path)

        with patch.object(deploy, "read_regular", side_effect=guarded_read):
            stage, _ = deploy.prepare(self.root)
        staged = {p.relative_to(stage).as_posix() for p in stage.rglob("*") if p.is_file()}
        self.assertFalse(staged.intersection(denied))
        self.assertFalse(any("config/" in p for p in staged))
        self.assertNotIn("closecall_server/lib/src/model.spy.yaml", staged)
        self.assertIn("closecall_server/lib/src/generated/protocol.yaml", staged)
        self.assertIn("closecall_server/migrations/20261004000100000/migration.sql", staged)
        self.assertIn("closecall_shared/lib/schedule.dart", staged)
        self.assertNotIn("closecall_server/pubspec.lock", staged)
        self.assertIn("pubspec.lock", staged)
        for package in ("closecall_server", "closecall_shared"):
            text = (stage / package / "pubspec.yaml").read_text()
            self.assertIn("resolution: workspace", text)
            self.assertNotIn("dev_dependencies:", text)
        self.assertIn("path: ../closecall_shared", (stage / "closecall_server/pubspec.yaml").read_text())
        self.assertIn("dartSdk: 3.13.5", (stage / "closecall_server/scloud.yaml").read_text())
        self.assertNotIn("serverpod generate", (stage / "closecall_server/scloud.yaml").read_text())
        self.assertNotIn("closecall_shared:", (stage / "pubspec.lock").read_text())
        manifest = json.loads((stage / deploy.MANIFEST).read_text())
        self.assertEqual(set(manifest["sourceSha256"]), set(reads) - {"closecall_server/scloud.yaml"})

    def test_rebuild_is_reproducible_and_explicit(self):
        stage, _ = deploy.prepare(self.root)
        before = {p.relative_to(stage).as_posix(): p.read_bytes()
                  for p in stage.rglob("*") if p.is_file()}
        with self.assertRaisesRegex(ValueError, "Stage exists"):
            deploy.prepare(self.root)
        deploy.prepare(self.root, replace=True)
        after = {p.relative_to(stage).as_posix(): p.read_bytes()
                 for p in stage.rglob("*") if p.is_file()}
        self.assertEqual(before, after)

    def test_nonignored_new_runtime_is_included_but_ignored_runtime_is_not(self):
        self.write("closecall_server/lib/new_endpoint.dart", "// runtime\n")
        self.write("closecall_server/lib/ignored.dart", "DO NOT READ\n")
        self.write(".gitignore", "closecall_server/lib/ignored.dart\n")
        stage, _ = deploy.prepare(self.root)
        self.assertTrue((stage / "closecall_server/lib/new_endpoint.dart").is_file())
        self.assertFalse((stage / "closecall_server/lib/ignored.dart").exists())

    def test_unowned_output_is_not_deleted(self):
        self.write(str(deploy.STAGE_PATH / "user-file.txt"), "keep")
        with self.assertRaises(ValueError):
            deploy.prepare(self.root, replace=True)
        self.assertEqual((self.root / deploy.STAGE_PATH / "user-file.txt").read_text(), "keep")

    def test_tracked_symlink_is_rejected_before_read(self):
        (self.root / "closecall_shared/lib/schedule.dart").unlink()
        (self.root / "closecall_shared/lib/schedule.dart").symlink_to("../../private.dart")
        self.write("private.dart", "DO NOT READ")
        with self.assertRaisesRegex(ValueError, "Symlinks"):
            deploy.prepare(self.root)

    def test_unreviewed_dependency_configuration_fails_closed(self):
        path = self.root / "closecall_server/pubspec.yaml"
        path.write_text(path.read_text() + "dependency_overrides:\n  serverpod: any\n")
        with self.assertRaisesRegex(ValueError, "Review new"):
            deploy.prepare(self.root)

    def test_config_hooks_fail_closed(self):
        self.write("closecall_server/scloud.yaml", deploy.SCLOUD_CONFIG + "# drift\n")
        with self.assertRaisesRegex(ValueError, "scloud.yaml"):
            deploy.prepare(self.root)

    def test_lock_preservation_guard_rejects_version_drift(self):
        original = (self.root / "closecall_server/pubspec.lock").read_text()
        deploy.verify_resolved_lock(original, deploy.workspace_lock(original))
        with self.assertRaisesRegex(ValueError, "changed a pinned"):
            deploy.verify_resolved_lock(original, original.replace('version: "4.0.3"', 'version: "4.0.4"'))


@unittest.skipUnless(os.environ.get("CLOSECALL_DEPLOY_INTEGRATION") == "1",
                     "Set CLOSECALL_DEPLOY_INTEGRATION=1 for offline Dart compile/archive checks")
class DartDeploymentTests(unittest.TestCase):
    def test_real_runtime_compiles_and_archive_is_allowlisted(self):
        dart = os.environ.get("DART", str(ROOT / ".tooling/flutter/bin/cache/dart-sdk/bin/dart"))
        version = subprocess.check_output([dart, "--version"], text=True, stderr=subprocess.STDOUT)
        self.assertIn("Dart SDK version: 3.13.5 ", version)
        # Use only public allowlisted runtime inputs to construct an isolated repo.
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            subprocess.run(["git", "init", "-q"], cwd=root, check=True)
            tracked = subprocess.check_output([
                "git", "ls-files", "--cached", "--others", "--exclude-standard", "-z",
                "--", "closecall_server", "closecall_shared",
            ], cwd=ROOT).decode().split("\0")
            for name in tracked:
                if deploy.allowed_runtime_path(name):
                    target = root / name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(deploy.read_regular(ROOT, name))
            config = root / "closecall_server/scloud.yaml"
            config.write_text(deploy.SCLOUD_CONFIG)
            subprocess.run(["git", "add", "closecall_server", "closecall_shared"], cwd=root, check=True)
            stage, _ = deploy.prepare(root)
            original_lock = (stage / "pubspec.lock").read_text()
            subprocess.run([dart, "pub", "get", "--offline"], cwd=stage, check=True)
            resolved_lock = (stage / "pubspec.lock").read_text()
            deploy.verify_resolved_lock(original_lock, resolved_lock)
            self.assertNotIn("  serverpod_cli:", resolved_lock)
            self.assertNotIn("  serverpod_test:", resolved_lock)
            self.assertNotIn("  test:", resolved_lock)
            subprocess.run([dart, "pub", "get", "--offline", "--enforce-lockfile"], cwd=stage, check=True)
            # Kernel compilation verifies all staged relative-package imports.
            # Native AOT requires `dart build` because Serverpod 4 dependencies
            # include native hooks; it is deliberately not represented as a
            # successful Cloud/Linux native build by this offline test.
            subprocess.run([dart, "compile", "kernel", "bin/main.dart", "-o", str(root / "runtime.dill")],
                           cwd=stage / "closecall_server", check=True)
            self.assertGreater((root / "runtime.dill").stat().st_size, 0)
            subprocess.run([
                dart, "--packages=" + str(ROOT / ".tooling/cloud-inspect/.dart_tool/package_config.json"),
                str(ROOT / "scripts/test_cloud_archive.dart"), str(stage),
            ], check=True)


if __name__ == "__main__":
    unittest.main()
